import { heuristicDraft, type BotContext } from "@/server/bot/parse";
import { devAssistant } from "./dev-assistant";
import { devIdleListing, devIdleOutreach } from "./dev-idle";
import { devTenderDraft, devTenderParse } from "./dev-tender";
import type { FakeLlmClient } from "./fake";

/**
 * Local-development stand-ins so flows work without an AI vendor. Output is plausible but made up,
 * and says so in `notes`; it is always reviewed by a person like real AI output.
 */
export function registerDevResponders(llm: FakeLlmClient): FakeLlmClient {
  llm.scriptChat("assistant", devAssistant);
  llm.respond("tender_parse", ({ lastUserMessage }: { lastUserMessage: string }) => devTenderParse(lastUserMessage));
  llm.respond("idle_listing", ({ lastUserMessage }: { lastUserMessage: string }) => devIdleListing(lastUserMessage));
  llm.respond("idle_outreach", ({ lastUserMessage }: { lastUserMessage: string }) => devIdleOutreach(lastUserMessage));
  llm.respond("tender_draft", ({ lastUserMessage }: { lastUserMessage: string }) => devTenderDraft(lastUserMessage));
  // Voice/text logs: the rule-based reader, using the context the prompt carries.
  llm.respond("voice_log", ({ system, lastUserMessage }: { system: string; lastUserMessage: string }) => {
    const json = system.slice(system.indexOf("CONTEXT_JSON ") + "CONTEXT_JSON ".length);
    return heuristicDraft(lastUserMessage, JSON.parse(json) as BotContext);
  });
  return llm.respond("ocr_extract", ({ lastUserMessage }: { lastUserMessage: string }) => {
    const type = /selected document type: ([a-z_]+)/.exec(lastUserMessage)?.[1] ?? null;
    const today = new Date();
    const iso = (d: Date) => d.toISOString().slice(0, 10);
    const issued = new Date(today.getTime() - 30 * 86_400_000);
    const expires = new Date(today.getTime() + 335 * 86_400_000);
    return {
      document_type_code: type,
      number: `DEV-${today.getUTCFullYear()}-${String(today.getUTCDate()).padStart(2, "0")}17`,
      issuer: "Read by local fake extractor",
      holder_name: null,
      vessel_name: null,
      issue_date: iso(issued),
      expiry_date: iso(expires),
      field_confidence: { number: 0.92, issuer: 0.55, issue_date: 0.66, expiry_date: 0.94 },
      date_format_assumed: null,
      notes: "Generated by the local fake extractor (no AI vendor configured).",
    };
  });
}
